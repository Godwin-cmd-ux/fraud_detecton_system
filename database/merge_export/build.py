#!/usr/bin/env python3
"""Build merge_export.sql from merge_template.sql and database_export.sql.

database_export.sql is a `pg_dump --clean` file: run as-is it would DROP every table. Only its
COPY data blocks are taken, re-pointed at the private _export_stage schema, and placed where the
template has `-- @@EXPORT_DATA@@`. Nothing else from the dump is executed.

    python3 database/merge_export/build.py [path/to/database_export.sql]
"""

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
DUMP = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'database_export.sql'
TEMPLATE = HERE / 'merge_template.sql'
OUT = HERE / 'merge_export.sql'

STAGED = {
    'drizzle.__drizzle_migrations': '_export_stage.drizzle_migrations',
    **{
        f'public.{t}': f'_export_stage.{t}'
        for t in (
            'admin_actions', 'admins', 'failed_login_log', 'failed_withdrawal_attempts',
            'login_attempts', 'security_questions', 'sessions', 'transactions', 'users',
            'ussd_requests', 'ussd_security_events', 'ussd_sessions',
        )
    },
}

COPY_RE = re.compile(r'^COPY (\S+) (\(.*\)) FROM stdin;$')


def copy_blocks(lines):
    """Yield (table, column list, data lines) for every COPY block in the dump."""
    i = 0
    while i < len(lines):
        m = COPY_RE.match(lines[i])
        if not m:
            i += 1
            continue
        table, cols = m.groups()
        i += 1
        rows = []
        while lines[i] != '\\.':
            rows.append(lines[i])
            i += 1
        yield table, cols, rows
        i += 1


def main():
    lines = DUMP.read_text(encoding='utf-8').split('\n')
    out, seen = [], set()
    for table, cols, rows in copy_blocks(lines):
        if table not in STAGED:
            sys.exit(f'{DUMP.name}: unexpected table {table}; add it to the template and STAGED')
        seen.add(table)
        out.append(f'-- {table}: {len(rows)} rows')
        out.append(f'COPY {STAGED[table]} {cols} FROM stdin;')
        out.extend(rows)
        out.append('\\.')
        out.append('')
    missing = set(STAGED) - seen
    if missing:
        sys.exit(f'{DUMP.name}: no data block for {", ".join(sorted(missing))}')

    template = TEMPLATE.read_text(encoding='utf-8')
    marker = '-- @@EXPORT_DATA@@'
    if template.count(marker) != 1:
        sys.exit(f'{TEMPLATE.name}: expected exactly one {marker}')
    header = (
        '-- GENERATED by database/merge_export/build.py from database_export.sql — edit\n'
        '-- merge_template.sql and rebuild instead of changing this file.\n'
    )
    OUT.write_text(header + template.replace(marker, '\n'.join(out)), encoding='utf-8')
    total = sum(len(r) for _, _, r in copy_blocks(lines))
    print(f'wrote {OUT.relative_to(ROOT)} ({len(seen)} tables, {total} rows)')


if __name__ == '__main__':
    main()
